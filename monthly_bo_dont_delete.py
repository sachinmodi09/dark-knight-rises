# Batch processing
def batch_process_stocks(tickers, batch_size=100):
    # Create a unique filename with timestamp for every run
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    output_file = f"Stocks_Analysis_{timestamp}.csv"

    num_batches = len(tickers) // batch_size + (1 if len(tickers) % batch_size != 0 else 0)

    for batch_num in range(num_batches):
        start_idx = batch_num * batch_size
        end_idx = min(start_idx + batch_size, len(tickers))
        tickers_batch = tickers[start_idx:end_idx]

        print(f"Processing batch {batch_num+1}/{num_batches} (Tickers {start_idx+1} to {end_idx})...")

        batch_data = []  # Temporary storage for the current batch

        for ticker in tickers_batch:
            print(f"Processing {ticker}...")
            time.sleep(random.uniform(1, 3))
            stock_data = process_stock_with_timeout(ticker)
            if not stock_data.empty:
                batch_data.append(stock_data)

        if batch_data:
            # Combine the current batch data
            batch_data_df = pd.concat(batch_data, ignore_index=True)

            # Filter rows meeting the condition
            filtered_data = batch_data_df[(batch_data_df['Highest High Highest Close'] == 'Yes')]

            # Append the filtered data to the output CSV file
            if not filtered_data.empty:
                with open(output_file, mode='a', newline='', encoding='utf-8') as f:
                    filtered_data.to_csv(f, index=False, header=f.tell() == 0)  # Add header only if the file is empty

            print(f"Batch {batch_num+1} appended to {output_file}.")

    print(f"All stocks processed and saved to {output_file}.")
    push_to_drive(output_file)


