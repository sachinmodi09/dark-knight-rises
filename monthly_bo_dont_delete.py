def build_marketcap_csv(save_path="/content/drive/MyDrive/stocks_market_cap.csv",
                        batch_size=50, delay=1):
    """
    Downloads all NSE tickers and fetches Yahoo Finance data.
    Overwrites the file used by downstream scripts.

    Columns: ['Symbols', 'marketcap', 'last_price', 'pe_ratio', 'pb_ratio', 'sector', 'currency']
    """
    # Step 1: Download all NSE symbols
    url = "https://archives.nseindia.com/content/equities/EQUITY_L.csv"
    print("📥 Downloading list of NSE symbols...")
    df_all = pd.read_csv(url)
    tickers = df_all["SYMBOL"].astype(str) + ".NS"

    results = []

    # Step 2: Batch fetch with rate control
    for i in tqdm(range(0, len(tickers), batch_size)):
        batch = tickers[i:i+batch_size]
        for t in batch:
            try:
                stock = yf.Ticker(t)
                info = stock.info

                market_cap = info.get("marketCap")
                last_price = info.get("currentPrice") or info.get("lastPrice")
                pe_ratio = info.get("trailingPE")
                pb_ratio = info.get("priceToBook")
                sector = info.get("sector")
                currency = info.get("currency")

                if market_cap:
                    market_cap_cr = round(market_cap / 1e7, 2)  # Convert to ₹ crores
                else:
                    market_cap_cr = None

                results.append({
                    "Symbols": t,  # match downstream name
                    "marketcap": market_cap_cr,
                    "last_price": last_price,
                    "pe_ratio": pe_ratio,
                    "pb_ratio": pb_ratio,
                    "sector": sector,
                    "currency": currency
                })

            except Exception:
                continue
        time.sleep(delay)

    # Step 3: Combine and save
    df_result = pd.DataFrame(results).sort_values("marketcap", ascending=False)

    os.makedirs(os.path.dirname(save_path), exist_ok=True)
    df_result.to_csv(save_path, index=False, encoding="utf-8-sig")

    print(f"\n✅ Saved {len(df_result)} tickers to {save_path}")
    return df_result

